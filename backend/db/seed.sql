-- Проверка: показываем количество товаров по категориям
SELECT 
    c.name AS 'Категория',
    COUNT(p.id) AS 'Кол-во товаров'
FROM categories c
LEFT JOIN products p ON p.category_id = c.id
GROUP BY c.id
ORDER BY c.id;